import agentpy as ap
import random
import matplotlib.pyplot as plt
import matplotlib.animation as animation

# -------- Get user input --------

num_agents = int(input("Enter number of agents: "))
grid_size = int(input("Enter grid size (e.g., 10 for 10x10): "))
num_steps = int(input("Enter number of steps: "))
min_distance = float(input("Enter minimum distance (e.g., 2): "))


# -------- Agent Definition --------

class RandomWalker(ap.Agent):

    def setup(self):
        self.position = (0, 0)
        self.path = []

    def propose_move(self, occupied):
        x, y = self.position
        width, height = self.model.p.grid_size
        radius = self.model.p.min_distance

        directions = [
            (1, 0), (-1, 0),
            (0, 1), (0, -1),
            (0, 0)
        ]
        random.shuffle(directions)

        candidates = []

        for dx, dy in directions:
            nx = max(0, min(width - 1, x + dx))
            ny = max(0, min(height - 1, y + dy))

            # Skip positions outside the permitted distance
            safe = True
            nearest_distance = float("inf")

            for ox, oy in occupied:
                if (ox, oy) == self.position:
                    continue

                distance_squared = (
                    (nx - ox) ** 2 + (ny - oy) ** 2
                )

                nearest_distance = min(
                    nearest_distance, distance_squared ** 0.5
                )

                if distance_squared < radius ** 2:
                    safe = False
                    break

            if safe:
                # Prefer moving away from nearby agents.
                # Random tie-breaking preserves random movement.
                candidates.append((nearest_distance, (nx, ny)))

        if not candidates:
            return self.position

        # Prefer the destination with the greatest separation.
        best_distance = max(score for score, pos in candidates)
        best_positions = [
            pos for score, pos in candidates
            if score == best_distance
        ]

        return random.choice(best_positions)


# -------- Model Definition --------

class RandomWalkModel(ap.Model):

    def setup(self):
        self.agents = ap.AgentList(
            self, self.p.agents, RandomWalker
        )

        width, height = self.p.grid_size

        # Initially place agents in distinct cells.
        cells = [
            (x, y)
            for x in range(width)
            for y in range(height)
        ]

        if self.p.agents > len(cells):
            raise ValueError(
                "There cannot be more agents than grid cells."
            )

        random.shuffle(cells)

        for agent, position in zip(self.agents, cells):
            agent.position = position
            agent.path = [position]

        # Shared occupancy record.
        self.grid = ap.Grid(
            self, self.p.grid_size, torus=False
        )
        self.grid.add_agents(self.agents)

    def step(self):
        # Snapshot of positions at the start of the step.
        occupied = [agent.position for agent in self.agents]

        # Every agent proposes before any agent moves.
        proposals = {
            agent: agent.propose_move(occupied)
            for agent in self.agents
        }

        # Resolve multiple agents selecting the same destination.
        destination_groups = {}

        for agent, destination in proposals.items():
            destination_groups.setdefault(
                destination, []
            ).append(agent)

        approved = {}

        for destination, contenders in destination_groups.items():
            if len(contenders) == 1:
                approved[contenders[0]] = destination
            else:
                # Choose one winner; others remain in place.
                winner = random.choice(contenders)
                approved[winner] = destination

                for agent in contenders:
                    if agent is not winner:
                        approved[agent] = agent.position

        # Commit all approved positions together.
        # This avoids transient occupancy conflicts.
        for agent in self.agents:
            self.grid.remove_agents([agent])

        for agent in self.agents:
            agent.position = approved.get(
                agent, agent.position
            )
            agent.path.append(agent.position)

        for agent in self.agents:
            self.grid.add_agents([agent])


# -------- Model Parameters --------

parameters = {
    "agents": num_agents,
    "grid_size": (grid_size, grid_size),
    "steps": num_steps,
    "min_distance": min_distance
}

# -------- Run Model --------

model = RandomWalkModel(parameters)
model.setup()

# -------- Animation --------

fig, ax = plt.subplots()

ax.set_xlim(0, grid_size)
ax.set_ylim(0, grid_size)
ax.set_xticks(range(grid_size + 1))
ax.set_yticks(range(grid_size + 1))
ax.set_aspect("equal")
ax.grid(True)

scat = ax.scatter([], [], s=100)

lines = [
    ax.plot([], [], linewidth=1)[0]
    for agent in model.agents
]


def update(frame):
    model.step()

    x = [agent.position[0] + 0.5 for agent in model.agents]
    y = [agent.position[1] + 0.5 for agent in model.agents]

    scat.set_offsets(list(zip(x, y)))

    for agent, line in zip(model.agents, lines):
        path_x = [p[0] + 0.5 for p in agent.path]
        path_y = [p[1] + 0.5 for p in agent.path]

        line.set_data(path_x, path_y)

    return scat, *lines


ani = animation.FuncAnimation(
    fig,
    update,
    frames=num_steps,
    blit=True,
    repeat=False
)

