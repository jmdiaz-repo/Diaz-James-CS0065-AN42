def check_room(room, rooms):
    print(f"Agent checks Room {room}.")
    return rooms[room] == "Dirty"


def clean_room(room, rooms):
    print(f"Agent cleans Room {room}.")
    rooms[room] = "Clean"


def agent(rooms):
    current_room = "A"

    while True:
        if check_room(current_room, rooms):
            clean_room(current_room, rooms)
        else:
            print(f"Room {current_room} is already clean.")

        # Stop once both rooms are clean
        if all(state == "Clean" for state in rooms.values()):
            print("Both rooms are clean. Agent stops.")
            break

        # Move to the other room
        if current_room == "A":
            current_room = "B"
        else:
            current_room = "A"

        print(f"Agent moves to Room {current_room}.")


def get_initial_state(room):
    while True:
        state = input(
            f"Enter initial state of Room {room} (Dirty/Clean): "
        ).strip().capitalize()

        if state in ("Dirty", "Clean"):
            return state

        print("Invalid input. Please enter Dirty or Clean.")


# Get initial room states from the user
rooms = {
    "A": get_initial_state("A"),
    "B": get_initial_state("B")
}

print("\nInitial room states:")
for room, state in rooms.items():
    print(f"Room {room}: {state}")

print("\nStarting agent simulation...\n")
agent(rooms)

print("\nFinal room states:")
for room, state in rooms.items():
    print(f"Room {room}: {state}")